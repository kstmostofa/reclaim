import Foundation

/// Build output that the project's own tooling recreates on the next build.
public enum BuildCacheRules {
    static let reason = "Build output generated by the project's tooling."
    static let consequence = "Recreated automatically on the next build or dev-server start; that first build is slower."

    public static func all(home: String) -> [any Rule] {
        [
            named("build.next", "Next.js build cache", ".next", markers: ["package.json"]),
            named("build.nuxt", "Nuxt build cache", ".nuxt", markers: ["package.json"]),
            named("build.turbo", "Turborepo cache", ".turbo"),
            named("build.svelteKit", "SvelteKit build cache", ".svelte-kit", markers: ["package.json"]),
            named("build.parcel", "Parcel cache", ".parcel-cache"),
            named("build.dartTool", "Dart tool cache", ".dart_tool", markers: ["pubspec.yaml"]),
            named("build.pycache", "Python bytecode cache", "__pycache__"),
            named("build.rustTarget", "Rust build output", "target", markers: ["Cargo.toml"]),
            named("build.gradleProject", "Gradle project cache", ".gradle",
                  markers: ["build.gradle", "build.gradle.kts", "settings.gradle", "settings.gradle.kts"]),
            NamedEntryRule(
                id: "build.androidIntermediates", title: "Android build intermediates",
                names: ["intermediates"], parentName: "build",
                category: .buildCache, level: .safe,
                reason: "Intermediate Gradle build files. Built APKs and bundles in build/outputs are kept.",
                consequence: consequence
            ),
            LocationRule(
                id: "build.xcodeDerivedData", title: "Xcode DerivedData",
                path: home + "/Library/Developer/Xcode/DerivedData", matchChildren: true,
                category: .buildCache, level: .safe,
                reason: "Xcode's per-project build products and indexes.",
                consequence: "Xcode rebuilds and re-indexes the project the next time it is opened."
            ),
        ]
    }

    private static func named(_ id: String, _ title: String, _ name: String, markers: [String] = []) -> NamedEntryRule {
        NamedEntryRule(id: id, title: title, names: [name], siblingMarkers: markers,
                       category: .buildCache, level: .safe, reason: reason, consequence: consequence)
    }
}
